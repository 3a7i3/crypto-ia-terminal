"""Synthetic bounded pilot -> captured evidence -> reader -> real GET route.

No exchange I/O. Raw responses are generated by the explicit synthetic transport.
"""

import argparse
import json
from pathlib import Path
from tempfile import TemporaryDirectory

from fastapi.testclient import TestClient

from observability.market_venues.pilot.plan import PilotPlan
from observability.market_venues.pilot.runner import run_bounded_pilot
from observability.market_venues.pilot.synthetic import (
    SyntheticClock,
    SyntheticTransport,
)
from observability.market_venues.pilot.verify import verify_run
from observability.operator_api import app as api
from observability.operator_api.venue_comparison_reader import VenueComparisonReader


def generate_pilot_fixture(out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    previous = api._venue_comparison_reader
    try:
        with TemporaryDirectory(prefix="market-pilot539-synthetic-") as temporary:
            parent = Path(temporary) / "market-venue-pilot-runs"
            parent.mkdir(mode=0o700)
            clock = SyntheticClock()
            result = run_bounded_pilot(
                SyntheticTransport(clock),
                parent,
                source_sha="0" * 40,
                plan=PilotPlan(cycles=2),
                clock=clock,
                sleeper=clock.sleep,
                run_id="cross-stack-synthetic",
            )
            folder = parent / result["run_id"]
            verified = verify_run(folder)
            assert result["status"] == "COMPLETED"
            assert verified["capture_population_complete"]
            api._venue_comparison_reader = VenueComparisonReader(
                folder / "latest.json", now_fn=lambda: clock.wall / 1_000_000_000
            )
            with TestClient(api.app) as client:
                response = client.get("/api/operator/v1/venue-comparison")
            assert response.status_code == 200
            body = response.json()
            assert body["evidence_kind"] == "SYNTHETIC"
            assert body["source_counts"] == {
                "expected": 4,
                "supplied": 4,
                "available": 4,
            }
            assert body["freshness_classification"] == "FRESH"
            (out_dir / "T_market_pilot.json").write_text(
                json.dumps(
                    {"http_status": response.status_code, "body": body},
                    indent=2,
                    sort_keys=True,
                ),
                encoding="utf-8",
            )
    finally:
        api._venue_comparison_reader = previous


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    generate_pilot_fixture(parser.parse_args().out)
