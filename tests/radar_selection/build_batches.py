"""Builder of the SYNTHETIC R1-B evidence tree and radar-batch fixtures (invented values only).

    python -m tests.radar_selection.build_batches               # rewrite the scanner run, spec and batch
    python -m tests.radar_selection.build_batches --check       # compare, write nothing
    python -m tests.radar_selection.build_batches --refresh-bbo # regenerate the frozen BBO evidence

Evidence root: ``tests/radar_selection/evidence/``.

- ``scanner/runs/<run_id>/``: the five catalogue responses as raw bytes, in the
  official public shapes, written exactly as a Scanner run would keep them, with
  JSON fractional numbers (Kraken fees, MEXC contract size) so that the
  "raw bytes, never re-serialised" rule is exercised; plus the run ``manifest.json``
  in the format of ``scanner_universe.collect``.
- ``bbo/``: FROZEN synthetic BBO evidence: the journal manifests, the replayed
  windows and the ``bbo-composite-history`` anchor produced by
  ``radar_composite.bbo_pilot dry-run`` + ``replay`` + ``bbo_history build`` on the
  synthetic transport (no network). The journal records the git HEAD it ran at,
  so this part is not regenerated by default; ``--refresh-bbo`` rebuilds it and
  ``bbo/PROVENANCE.json`` records the commit. ``events.jsonl``/``frames.bin`` are
  not kept: the adapter never reads them.
- ``specs/`` and ``batches/``: the operator spec and the batch built from it by
  ``observability.radar_selection.batch_build`` (checked byte for byte).
"""
from __future__ import annotations

import hashlib
import json
import sys
import tarfile
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from tests.radar_selection import build_fixtures as r0

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / "tests" / "radar_selection" / "evidence"
RUN_ID = "20261117T163500Z"
RUN = f"scanner/runs/{RUN_ID}"
# The synthetic BBO dry-run grid (bbo_pilot.DRY_RUN_START_MS): BTC 2 windows, ATOM 3 windows.
WINDOW_START = 1_795_128_000_000
EVALUATION_MS = 1_795_128_900_000      # end of the ATOM coverage
RECEIVED_MS = EVALUATION_MS - 600_000  # catalogues received 10 min before (fresh: max 35 min)
ANCHOR_NOW = datetime(2026, 11, 17, 17, 0, 0, tzinfo=timezone.utc)
BBO_PAIRS = ("BTC", "ATOM")
SPEC = "specs/r1b_syn_spec.json"
BATCH = "batches/r1b_syn_01_btc_atom.json"

URLS = {
    "mexc_spot_exchange_info": "https://api.mexc.com/api/v3/exchangeInfo",
    "mexc_contract_detail": "https://contract.mexc.com/api/v1/contract/detail",
    "kraken_asset_pairs": "https://api.kraken.com/0/public/AssetPairs",
    "kraken_assets": "https://api.kraken.com/0/public/Assets",
    "kraken_futures_instruments": "https://futures.kraken.com/derivatives/api/v3/instruments",
}


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _json(doc) -> bytes:
    # Plain json.dumps, as a venue would serve it: floats stay JSON fractional numbers.
    return json.dumps(doc, indent=1, sort_keys=False).encode("utf-8")


def catalogue_bodies() -> dict:
    """R0 'calm' catalogues with the fractional numbers the official shapes carry."""
    pairs = r0.kraken_pairs(r0.BASE_KRAKEN_SPOT)
    for row in pairs["result"].values():
        row["fees"] = [[0, 0.26], [50000, 0.24]]
        row["ordermin"] = "0.0001"
    perp = r0.mexc_perp(r0.BASE_MEXC_PERP)
    for row in perp["data"]:
        row["contractSize"] = 0.0001
        row["takerFeeRate"] = 0.0002
    kperp = r0.kraken_perp(r0.BASE_KRAKEN_PERP)
    for row in kperp["instruments"]:
        row["tickSize"] = 0.5
    return {
        "mexc_spot_exchange_info": r0.mexc_spot(r0.BASE_MEXC_SPOT),
        "mexc_contract_detail": perp,
        "kraken_asset_pairs": pairs,
        "kraken_assets": r0.kraken_assets(),
        "kraken_futures_instruments": kperp,
    }


def scanner_files() -> dict:
    """{relative path: bytes} of one Scanner run (format of scanner_universe.collect)."""
    from observability.scanner_universe.collect import encode
    files, docs = {}, {}
    for name, body in catalogue_bodies().items():
        raw = _json(body)
        files[f"{RUN}/{name}.json"] = raw
        docs[name] = {"url": URLS[name], "received_ms": RECEIVED_MS, "error": None, "http_status": 200,
                      "sha256": _sha(raw), "bytes": len(raw)}
    manifest = {"run_id": RUN_ID, "started_ms": RECEIVED_MS - 2_000, "documents": docs,
                "evaluated_ms": RECEIVED_MS + 1_000}
    files[f"{RUN}/manifest.json"] = encode(manifest)
    return files


def policy() -> dict:
    return {"venues": ["kraken", "mexc"], "market_types": ["SPOT", "PERPETUAL"],
            "quotes": ["USDT", "USD", "USDC"], "asset_classes": ["CRYPTO"], "deny": []}


def spec_doc(evidence: Path) -> dict:
    sources = []
    for pair in BBO_PAIRS:
        d = f"bbo/BBO-{pair}-DRY"
        windows = sorted((evidence / d / "replay").glob("window_*_primary.json"),
                         key=lambda p: int(p.name.split("_")[1]))
        sources.append({
            "pair": pair, "anchor_ref": "bbo/bbo-composite-history.json",
            "anchor_sha256": _sha((evidence / "bbo" / "bbo-composite-history.json").read_bytes()),
            "manifest_ref": f"{d}/manifest.json",
            "manifest_sha256": _sha((evidence / d / "manifest.json").read_bytes()),
            "window_refs": [f"{d}/replay/{w.name}" for w in windows],
        })
    return {
        "spec_schema": "radar-batch-spec/1.0.0", "dataset_id": "R1B-SYN-01-BTC-ATOM",
        "description": "R1-B SYNTHETIC : catalogues Scanner inventés et fenêtres BBO du transport simulé",
        "evidence_kind": "SYNTHETIC", "evaluation_time_ms": EVALUATION_MS, "policy": policy(),
        "source_access": {m: {"state": "ACCESSIBLE", "reason": None}
                          for m in ("MEXC_SPOT", "MEXC_PERPETUAL", "KRAKEN_SPOT", "KRAKEN_PERPETUAL")},
        "previous_universe": None, "scanner_run": RUN,
        "scanner_manifest_sha256": _sha(scanner_files()[f"{RUN}/manifest.json"]),
        "bbo_sources": sources,
    }


def read_blobs(evidence: Path, wanted) -> dict:
    out = {}
    for ref in wanted:
        p = evidence / ref
        if p.is_file():
            out[ref] = p.read_bytes()
    return out


def batch_bytes(evidence: Path, extra: dict | None = None) -> bytes:
    from observability.radar_selection.batch_build import build_batch, spec_refs
    from observability.radar_selection.fixture import canonical
    spec = spec_doc(evidence)
    blobs = {**read_blobs(evidence, spec_refs(spec)), **(extra or {})}
    return canonical(build_batch(spec, blobs))


def generated(evidence: Path = EVIDENCE) -> dict:
    files = scanner_files()
    blobs = {**files}
    files[SPEC] = (json.dumps(spec_doc(evidence), indent=1, sort_keys=True, ensure_ascii=False) + "\n").encode()
    files[BATCH] = batch_bytes(evidence, blobs)
    return files


def refresh_bbo(evidence: Path = EVIDENCE) -> None:
    """Regenerate the frozen BBO evidence with the synthetic transport (no network)."""
    import subprocess
    from observability.radar_composite import bbo_history as h
    from observability.radar_composite import bbo_pilot as bp
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True,
                          check=True).stdout.strip()
    with tempfile.TemporaryDirectory() as tmp:
        dirs, archives = [], []
        for pair in BBO_PAIRS:
            out = Path(tmp) / f"BBO-{pair}-DRY"
            bp.dry_run(pair, out)
            bp.replay(out)
            archive = Path(tmp) / f"BBO-{pair}-DRY.tar.gz"
            with tarfile.open(archive, "w:gz") as t:
                t.add(out, arcname=out.name)
            dirs.append(out)
            archives.append(archive)
        anchor = h.build(dirs, archives, "R1B-SYN", now=ANCHOR_NOW)
        target = evidence / "bbo"
        target.mkdir(parents=True, exist_ok=True)
        (target / "bbo-composite-history.json").write_text(json.dumps(anchor, indent=1, sort_keys=True) + "\n")
        for d in dirs:
            dest = target / d.name / "replay"
            dest.mkdir(parents=True, exist_ok=True)
            (target / d.name / "manifest.json").write_bytes((d / "manifest.json").read_bytes())
            for w in sorted((d / "replay").glob("window_*_primary.json")):
                (dest / w.name).write_bytes(w.read_bytes())
        (target / "PROVENANCE.json").write_text(json.dumps({
            "generator": "tests/radar_selection/build_batches.py --refresh-bbo",
            "transport": "bbo_pilot.FakeVenues (SYNTHETIC, no network)",
            "git_head_at_generation": head,
            "note": "events.jsonl and frames.bin are not kept; the adapter only reads manifests, windows and anchor",
        }, indent=1, sort_keys=True) + "\n")


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--refresh-bbo" in argv:
        refresh_bbo()
    files = generated()
    diff = []
    for rel, data in sorted(files.items()):
        p = EVIDENCE / rel
        if not p.exists() or p.read_bytes() != data:
            diff.append(rel)
            if "--check" not in argv:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_bytes(data)
    print(("différences : " if "--check" in argv else "écrits : ") + (", ".join(diff) or "aucun"))
    return 1 if diff and "--check" in argv else 0


if __name__ == "__main__":
    raise SystemExit(main())
